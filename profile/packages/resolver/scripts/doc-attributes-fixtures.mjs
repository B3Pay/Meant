// Writes test/fixtures/doc-attributes/<name>.doc-attributes.json: what `didToDocAttributes` of @candid-core/cli answers
// for each <name>.did there, and SOURCE.json, which says which build answered. The responses are candid-core's
// output, the input of src/doc-annotations.mjs, so they are generated, never edited by hand.
//
// By default the installed @candid-core/cli answers (pinned in package.json; 0.4.0 is the first release with
// didToDocAttributes). To try an unreleased candid-core, point --cli at a build of its npm package
// (crates/candid-core-wasm/npm, built with its `npm run build`):
//
//   node scripts/doc-attributes-fixtures.mjs
//   node scripts/doc-attributes-fixtures.mjs --cli <candid-core>/crates/candid-core-wasm/npm/lib/index.js --commit <sha>
import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const PKG = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const DIR = path.join(PKG, "test/fixtures/doc-attributes");

const args = process.argv.slice(2);
const option = (name) => {
  const i = args.indexOf(name);
  return i === -1 ? undefined : args[i + 1];
};
const cliPath = option("--cli");
const cli = await import(cliPath === undefined ? "@candid-core/cli" : pathToFileURL(path.resolve(cliPath)).href);
if (typeof cli.didToDocAttributes !== "function") {
  console.error("this @candid-core/cli has no didToDocAttributes; give --cli <path to a build that has it>");
  process.exit(2);
}
// The installed package sits wherever npm hoisted it (the workspace root's node_modules, as a rule).
const cliRoot = cliPath === undefined ? path.dirname(createRequire(path.join(PKG, "package.json")).resolve("@candid-core/cli/package.json")) : path.join(path.dirname(path.resolve(cliPath)), "..");
const manifest = JSON.parse(await readFile(path.join(cliRoot, "package.json"), "utf8"));
const wasm = await readFile(path.join(cliRoot, "wasm/candid_core_wasm_bg.wasm"));

const files = {};
for (const name of (await readdir(DIR)).filter((f) => f.endsWith(".did")).sort()) {
  const text = await readFile(path.join(DIR, name), "utf8");
  const response = await cli.didToDocAttributes({ entry: name, files: { [name]: text } });
  const out = name.replace(/\.did$/, ".doc-attributes.json");
  await writeFile(path.join(DIR, out), `${JSON.stringify(response, null, 2)}\n`);
  files[out] = { from: name, ok: response.ok };
}
const source = {
  format: "candid-profile-doc-attributes-fixtures",
  notes: [
    "Responses of didToDocAttributes (candid-core doc attributes v1) for the .did files beside them. Generated by packages/resolver/scripts/doc-attributes-fixtures.mjs; never edit by hand.",
    cliPath === undefined
      ? "Written by the installed @candid-core/cli."
      : "Written by a local build of candid-core's npm package, not a published release.",
  ],
  cli: { name: manifest.name, version: manifest.version, ...(option("--commit") ? { candid_core_commit: option("--commit") } : {}), wasm_sha256: createHash("sha256").update(wasm).digest("hex") },
  files,
};
await writeFile(path.join(DIR, "SOURCE.json"), `${JSON.stringify(source, null, 2)}\n`);
console.log(`wrote ${Object.keys(files).length} responses to ${path.relative(process.cwd(), DIR)}`);
