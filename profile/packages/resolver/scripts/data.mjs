// Copies the profile schema (spec/) and the standard packs (packs/) into this package's data/ directory, so that
// the package carries them as data and runs outside this repository's layout (`@meantjs/profile/schema.json`,
// `@meantjs/profile/packs/<name>.profile.json`). The repository's spec/ and packs/ stay the source of truth
// (W0's paths); the copies are generated, never edited by hand.
//
// It also compiles the schema ahead of time into data/profile-v0.validate.mjs (ajv's standalone code), so that
// validating against the shipped schema generates no code at run time: no `new Function`, so no CSP 'unsafe-eval'.
//
//   node scripts/data.mjs           write data/ from spec/ and packs/, removing copies whose source is gone
//   node scripts/data.mjs --check   write nothing; exit 1 if data/ differs (test/data.test.mjs runs this check)
import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const PKG = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ROOT = path.resolve(PKG, "../..");

/** [source, copy] pairs, both absolute. `root` and `pkg` default to this repository and this package (tests move them). */
export async function dataFiles({ root = ROOT, pkg = PKG } = {}) {
  const packs = (await readdir(path.join(root, "packs"))).filter((f) => f.endsWith(".profile.json")).sort();
  return [
    [path.join(root, "spec/profile-v0.schema.json"), path.join(pkg, "data/profile-v0.schema.json")],
    ...packs.map((f) => [path.join(root, "packs", f), path.join(pkg, "data/packs", f)]),
  ];
}

const require = createRequire(import.meta.url);
const VALIDATOR = "data/profile-v0.validate.mjs";
/** ajv's one run-time helper in the generated code, which it writes as a CommonJS `require`. */
const UCS2_REQUIRE = 'require("ajv/dist/runtime/ucs2length").default';

/**
 * The validator module for a schema document: ajv's standalone code for the same options the run-time compiler uses
 * (src/schema-core.mjs), as an ES module with no import. ajv's ESM output still `require`s its string-length helper;
 * that call is replaced by a local function that counts code points the same way (test/schema-precompiled.test.mjs
 * compares the two). Any other `require` fails here rather than in a consumer's bundle.
 */
export function validatorModule(schemaText) {
  const Ajv2020 = require("ajv/dist/2020.js").default;
  const standaloneCode = require("ajv/dist/standalone/index.js").default;
  const ajv = new Ajv2020({ allErrors: true, strict: true, code: { source: true, esm: true } });
  let code = standaloneCode(ajv, ajv.compile(JSON.parse(schemaText)));
  code = code.replaceAll(UCS2_REQUIRE, "ucs2length");
  if (/\brequire\s*\(/.test(code)) throw new Error(`the standalone validator still requires a module: ${code.match(/\brequire\s*\([^)]*\)/)[0]}`);
  const { version } = require("ajv/package.json");
  return [
    `// Generated by packages/resolver/scripts/data.mjs from spec/profile-v0.schema.json with ajv ${version} (standalone code).`,
    "// Do not edit: run `npm run data -w packages/resolver`. The validator generates no code at run time.",
    code,
    "// Code points, counted as ajv's runtime ucs2length counts them: a surrogate pair is one, a lone surrogate is one.",
    "function ucs2length(s) {",
    "  let n = 0;",
    "  for (const _ of s) n++;",
    "  return n;",
    "}",
    "",
  ].join("\n");
}

/** Copies in data/packs whose source pack is gone (deleted or renamed), absolute. */
async function orphans(files, pkg) {
  const expected = new Set(files.map(([, copy]) => copy));
  const present = await readdir(path.join(pkg, "data/packs")).catch(() => []);
  return present.map((f) => path.join(pkg, "data/packs", f)).filter((f) => !expected.has(f));
}

/** Write every copy and remove the orphans. Returns the copies written and the files removed, relative to `pkg`. */
export async function writeData({ root = ROOT, pkg = PKG } = {}) {
  const files = await dataFiles({ root, pkg });
  const written = [];
  for (const [src, copy] of files) {
    await mkdir(path.dirname(copy), { recursive: true });
    await writeFile(copy, await readFile(src));
    written.push(path.relative(pkg, copy));
  }
  await writeFile(path.join(pkg, VALIDATOR), validatorModule(await readFile(files[0][0], "utf8")));
  written.push(VALIDATOR);
  const removed = [];
  for (const f of await orphans(files, pkg)) {
    await rm(f);
    removed.push(path.relative(pkg, f));
  }
  return { written, removed };
}

/** The copies that are missing or differ from their source, and the copies in data/packs with no source. */
export async function staleData({ root = ROOT, pkg = PKG } = {}) {
  const stale = [];
  const files = await dataFiles({ root, pkg });
  for (const [src, copy] of files) {
    const want = await readFile(src);
    const have = await readFile(copy).catch(() => null);
    if (have === null || !want.equals(have)) stale.push(path.relative(pkg, copy));
  }
  const validator = await readFile(path.join(pkg, VALIDATOR), "utf8").catch(() => null);
  if (validator !== validatorModule(await readFile(files[0][0], "utf8"))) stale.push(VALIDATOR);
  for (const f of await orphans(files, pkg)) stale.push(`${path.relative(pkg, f)} (no source)`);
  return stale;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.includes("--check")) {
    const stale = await staleData();
    if (stale.length) {
      console.error(`data/ is out of date (run \`npm run data -w packages/resolver\`): ${stale.join(", ")}`);
      process.exit(1);
    }
    console.log("data/ matches spec/ and packs/, and the precompiled validator matches the schema");
  } else {
    const { written, removed } = await writeData();
    for (const f of written) console.log(`wrote ${f}`);
    for (const f of removed) console.log(`removed ${f} (its source is gone)`);
  }
}
