// Builds the SNS golden documents and their review file from test/sns-golden/cases.mjs. Pure: nothing is written here
// (scripts/generate-golden.mjs writes, test/sns.test.mjs compares).

import { encodeValidatorResult, snsValidatorRendering } from "../../src/sns.mjs";
import { LEDGERS, encodeCall, hexOf, icrc1, icrc2, refsFor, LEDGER_DID } from "../helpers.mjs";
import { DAPP_DID, bareDapp, dapp, functionDebug, governanceRendering, sha256Hex } from "../sns-helpers.mjs";
import { CASES, WRAPPED_EXAMPLE } from "./cases.mjs";

/** The resolved form, the .did the arguments are encoded with, and the refs of one case. */
export function sourceOf(c) {
  switch (c.source) {
    case "icrc1":
    case "icrc2":
      return { resolved: c.source === "icrc1" ? icrc1 : icrc2, did: LEDGER_DID, refs: c.noRefs ? {} : refsFor(LEDGERS[c.ledger]) };
    case "dapp":
      return { resolved: dapp, did: DAPP_DID, refs: {} };
    case "bare":
      return { resolved: bareDapp, did: DAPP_DID, refs: {} };
    default:
      throw new Error(`unknown source ${c.source}`);
  }
}

/**
 * The resolved forms of the hypothetical dapp, as the Rust tests read them (`resolved/<name>.resolved.json`). The pack
 * cases use the committed `fixtures/*.resolved.json` of the repository.
 */
export const RESOLVED_FOR_RUST = { dapp, bare: bareDapp };

export const resolvedJson = (name) => `${JSON.stringify(RESOLVED_FOR_RUST[name], null, 2)}\n`;

export function payloadOf(c) {
  return encodeCall(c.encodeAs ?? c.method, c.args, sourceOf(c).did);
}

export function buildSnsGolden(c) {
  const { resolved, refs } = sourceOf(c);
  const payload = payloadOf(c);
  const reply = snsValidatorRendering({ payload, resolved, method: c.method, refs });
  return {
    id: c.id,
    why: c.why,
    source: c.source,
    method: c.method,
    ...(c.encodeAs ? { encoded_as: c.encodeAs } : {}),
    args: c.args,
    refs,
    payload_hex: hexOf(payload),
    payload_sha256: sha256Hex(payload),
    reply: { ...reply },
    reply_hex: hexOf(encodeValidatorResult(reply)),
  };
}

/** The wrapped example: what `get_proposal` would return as `payload_text_rendering` for one case. */
export function wrappedExample() {
  const c = CASES.find((x) => x.id === WRAPPED_EXAMPLE.caseId);
  const g = buildSnsGolden(c);
  const fn = functionDebug({ target: WRAPPED_EXAMPLE.target, targetMethod: WRAPPED_EXAMPLE.targetMethod, validator: WRAPPED_EXAMPLE.validator, validatorMethod: WRAPPED_EXAMPLE.validatorMethod });
  return governanceRendering(fn, payloadOf(c), g.reply.Ok);
}

export function renderSnsReview(cases) {
  const out = [
    "# Golden SNS validator renderings",
    "",
    "Generated by `scripts/generate-golden.mjs` from `cases.mjs`; do not edit. Each case is one `ExecuteGenericNervousSystemFunction` payload and the reply of a validator generated from a profile: `Ok` is the text voters read under governance's `## Payload:` heading, `Err` rejects the proposal.",
    "",
    "## How governance shows it",
    "",
    `The whole \`payload_text_rendering\` SNS governance stores for case \`${WRAPPED_EXAMPLE.caseId}\`, registered as generic function 1000 on the dapp \`${WRAPPED_EXAMPLE.target}\` (layout from dfinity/ic 649156c, \`rs/sns/governance/src/proposal.rs\`):`,
    "",
    "~~~markdown",
    wrappedExample(),
    "~~~",
    "",
  ];
  for (const c of cases) {
    const g = buildSnsGolden(c);
    out.push(`## ${c.id}`, "", c.why, "", `Validator for \`${c.method}\` (${c.source})${c.encodeAs ? `, payload encoded for \`${c.encodeAs}\`` : ""}, payload sha256 \`${g.payload_sha256}\`:`, "", "```candid", c.args, "```", "");
    if ("Ok" in g.reply) out.push("**Ok** (Markdown source):", "", "~~~markdown", g.reply.Ok, "~~~", "");
    else out.push(`**Err:** \`${g.reply.Err}\``, "");
  }
  return `${out.join("\n")}\n`;
}
