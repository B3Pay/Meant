// Builds the golden documents and the review file from test/golden/cases.mjs. Pure: nothing is written here
// (scripts/generate-golden.mjs writes, test/golden.test.mjs compares).

import { LEDGERS, encodeCall, hexOf, icrc1, icrc2, refsFor } from "../helpers.mjs";
import { icrc21ConsentMessage, toJson } from "../../src/index.mjs";

export function buildGolden(c) {
  const ledger = LEDGERS[c.ledger];
  const resolved = c.pack === "icrc1" ? icrc1 : icrc2;
  const arg = encodeCall(c.method, c.args);
  const out = { id: c.id, why: c.why, pack: c.pack, method: c.method, ledger: { id: c.ledger, ...ledger }, args: c.args, arg_hex: hexOf(arg) };
  for (const [form, spec] of [["fields", { FieldsDisplay: null }], ["generic", { GenericDisplay: null }]]) {
    const user_preferences = { metadata: { language: "en", utc_offset_minutes: c.utcOffsetMinutes ?? null }, device_spec: spec }; // the offset is also sent with the fields form, which must ignore it
    const response = icrc21ConsentMessage({ method: c.method, arg, user_preferences }, { resolved, refs: refsFor(ledger) });
    out[form] = { request: { user_preferences }, response: toJson(response) };
  }
  return out;
}

const zone = (m) => `UTC${m > 0 ? "+" : "-"}${String(Math.floor(Math.abs(m) / 60)).padStart(2, "0")}:${String(Math.abs(m) % 60).padStart(2, "0")}`;

export function renderReview(cases) {
  const out = [
    "# Golden consent messages",
    "",
    "Generated by `scripts/generate-golden.mjs` from `cases.mjs`; do not edit. Every ICRC-1 / ICRC-2 update method on the three eval ledgers (TKA 8, TKB 6, TKC 18 decimals). For each case: the call, the generic message as Markdown source, and the fields message row by row, with the metadata of each response.",
    "",
  ];
  for (const c of cases) {
    const g = buildGolden(c);
    const fields = g.fields.response.Ok.consent_message.FieldsDisplayMessage;
    const generic = g.generic.response.Ok;
    out.push(`## ${c.id}`, "", c.why, "", `Call: \`${c.method}\` on ${c.ledger} (${g.ledger.decimals} decimals)${c.utcOffsetMinutes ? `, user time zone ${zone(c.utcOffsetMinutes)}` : ""}`, "", "```candid", c.args, "```", "");
    out.push("**Generic display message** (Markdown source):", "", "~~~markdown", generic.consent_message.GenericDisplayMessage, "~~~", "", `metadata: ${JSON.stringify(generic.metadata)}`, "");
    out.push("**Fields display message:**", "", `intent: ${fields.intent}`, "");
    for (const [label, value] of fields.fields) {
      const [kind, body] = Object.entries(value)[0];
      out.push(`- ${label}: ${kind} ${JSON.stringify(body)}`);
    }
    out.push("", `metadata: ${JSON.stringify(g.fields.response.Ok.metadata)}`, "");
  }
  return `${out.join("\n")}\n`;
}
